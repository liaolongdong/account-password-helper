/**
 * 密码学参数的单一真源
 *
 * PBKDF2 的轮数**不随密文落盘**：主密码校验值（`deriveVerifierHash`）、字段加密密钥
 * （`deriveEncryptionKey`）、备份文件（`utils/backupExport.ts`）与身份信息库备份
 * （`utils/identity/backup.ts`）四条派生路径各自只把 salt 写进存储，轮数是它们与
 * 调用方之间的带外约定。于是任何一处与其他处不一致都是**静默故障**——换设备后校验值
 * 对不上、旧备份解不开、导出与导入各自算出不同的密钥，而报错只会停在
 * 「解密失败」这一层，不会指向轮数。
 *
 * 所以这个数量全仓只允许有一个定义处，其余位置一律 import。
 * `tests/architecture/securityDefaults.test.ts` 同时钉住两件事：取到的值恒为该值、
 * 且定义处只有一个（换成可被入参影响的写法、或另起一份本地常量都会变红）。
 *
 * 提升强度属于**格式变更**而非改一个数字：必须先把轮数写进校验值记录与备份容器
 * （否则新数据再也解不开），并提供旧数据的平滑迁移与回滚路径。
 */

/**
 * PBKDF2 迭代轮数（SHA-256）
 *
 * 取 OWASP 密码存储速查表对 PBKDF2-HMAC-SHA256 给出的推荐下限 600,000 次；
 * 与既有密文/校验值格式绑定，改动即格式变更（见文件头说明）。
 */
export const PBKDF2_ITERATIONS = 600_000;
