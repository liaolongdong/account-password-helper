// ---------- 主流程 ----------
const zhArticles = readArticles(zhDir);
const enArticles = readArticles(enDir);
const enSlugs = new Set(enArticles.map(a => a.slug));
for (const a of zhArticles) {
  if (!enSlugs.has(a.slug)) throw new Error(`缺少英文对应文章: ${a.slug}`);
}
const enBySlug = Object.fromEntries(enArticles.map(a => [a.slug, a]));

mkdirSync(outDir, { recursive: true });
let written = 0;

for (const zh of zhArticles) {
  const en = enBySlug[zh.slug];
  const zhUrl = `${SITE}/blog/${zh.slug}.html`;
  const enUrl = `${SITE}/blog/${en.slug}.en.html`;
  writeFileSync(
    path.join(outDir, `${zh.slug}.html`),
    articlePage(zh, {
      lang: 'zh-CN',
      selfUrl: zhUrl,
      altUrl: enUrl,
      backHref: './index.html',
      backLabel: '← 博客首页',
      switchLabel: 'English',
      footerNote: `Account Password Helper · <a href="${SITE}/">官网</a> · <a href="https://github.com/liaolongdong/account-password-helper">GitHub</a> · <a href="https://chromewebstore.google.com/detail/account-password-helper/fgimkdodpjfkddmildjieojpfakpanli">Chrome 应用商店</a>`,
    }),
  );
  writeFileSync(
    path.join(outDir, `${en.slug}.en.html`),
    articlePage(en, {
      lang: 'en',
      selfUrl: enUrl,
      altUrl: zhUrl,
      backHref: './index.en.html',
      backLabel: '← Blog Home',
      switchLabel: '中文',
      footerNote: `Account Password Helper · <a href="${SITE}/en.html">Website</a> · <a href="https://github.com/liaolongdong/account-password-helper">GitHub</a> · <a href="https://chromewebstore.google.com/detail/account-password-helper/fgimkdodpjfkddmildjieojpfakpanli">Chrome Web Store</a>`,
    }),
  );
  written += 2;
}

